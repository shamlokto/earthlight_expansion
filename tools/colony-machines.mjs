// Builds js/colony/data/machines.js from the expansion's unit data (js/expansion/data/units.json),
// so the colony's production list matches the expansion's (owner, 2026-11-03: "production for
// Earth Light units as well, just like the expansion"; "credits and parts can build ships/units").
// Same market rule as js/expansion/campaign.js marketTypes(); prices from its price() (value × hp).
//   node tools/colony-machines.mjs
import fs from 'fs';
const units = JSON.parse(fs.readFileSync(new URL('../js/expansion/data/units.json', import.meta.url))).units;
const STRUCTURE = 52, BATTERIES = [23, 24];
const family = (t) => { let x = t; for (let i = 0; i < 4; i++) { const u = units[x]; const n = u.armed ?? u.empty ?? u.formOf; if (n === undefined) break; x = n; } return x; };
const market = units.filter((t) => !t.cut && !t.unionOnly && (t.move > 0 || BATTERIES.includes(t.type)) && !(t.type >= STRUCTURE && t.type < 58)
  && t.armed === undefined && t.formOf === undefined && t.empty === undefined);
const CLASS = (c) => (c <= 4 ? 'ships' : c === 8 ? 'hu' : c === 9 || c === 10 ? 'planes' : c === 11 || c === 12 ? 'armour' : 'support');
const out = market.map((u) => {
  const price = Math.max(1, u.value) * u.hp, series = units[family(u.type)].series || u.series || 'original';
  const cls = CLASS(u.category), kai = series === 'kai';
  // where: capital ships at the Shipyard, everything else at the Arsenal
  const at = cls === 'ships' ? 'shipyard' : 'arsenal';
  // tier: what research opens it (data/tech.js): 1 at once, 2 'machineworks', 3 'heavyworks', Kai 'kai'
  const tier = kai ? 4 : price <= 16 ? 1 : price <= 40 ? 2 : 3;
  return { type: u.type, name: u.name, code: (u.code || '').trim(), cls, category: u.category, hp: u.hp, move: u.move, evasion: u.evasion,
    attack: Math.max(0, ...(u.info?.attack || [0])), defence: u.info?.defence ?? 0, price, at, tier, series,
    unique: !!(units[family(u.type)].unique || u.unique) };
});
const body = `// Generated by tools/colony-machines.mjs from js/expansion/data/units.json: the Earth Light machines
// the colony can build (the expansion's market list), with the expansion's price (value × hp).
// cls: hu | planes | armour | ships | support · at: arsenal | shipyard · tier: 1 at once, 2 Machine Works,
// 3 Heavy Works, 4 Kai Refits (data/tech.js) · attack / defence: the info screen's numbers.
// Cost to build in the colony: credits = price × 10, parts = price (MACHINE_COST).
export const MACHINES = ${JSON.stringify(out, null, 0).replace(/},{/g, '},\n  {').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')};
export const MACHINE = Object.fromEntries(MACHINES.map((m) => [m.type, m]));
export const MACHINE_COST = (m) => ({ credits: m.price * 10, parts: m.price });
`;
fs.writeFileSync(new URL('../js/colony/data/machines.js', import.meta.url), body);
console.log(`${out.length} machines: ` + ['hu', 'planes', 'armour', 'ships', 'support'].map((c) => `${c} ${out.filter((m) => m.cls === c).length}`).join(', ')
  + ' · tiers ' + [1, 2, 3, 4].map((t) => `${t}:${out.filter((m) => m.tier === t).length}`).join(' '));
